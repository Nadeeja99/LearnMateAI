/**
 * Opens the browser print dialog with a styled, printable copy of a summary (save as PDF).
 *
 * contentHtml must be markup React already rendered (e.g. the Markdown container's innerHTML):
 * React escapes text and the Markdown renderer allows no raw HTML, so it is safe to embed.
 */
export function printSummary(contentHtml: string): void {
  // Create a hidden iframe for printing
  const iframe = document.createElement('iframe');
  iframe.style.position = 'absolute';
  iframe.style.left = '-9999px';
  iframe.style.top = '-9999px';
  iframe.style.width = '0px';
  iframe.style.height = '0px';
  iframe.style.border = 'none';
  iframe.style.visibility = 'hidden';
  
  document.body.appendChild(iframe);

  // Create the HTML content for PDF
  const htmlContent = `
    <!DOCTYPE html>
    <html>
      <head>
        <meta charset="UTF-8">
        <title>Document Summary - LearnMate AI</title>
        <style>
          @page {
            margin: 1in;
            size: A4;
          }
          body {
            font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif;
            line-height: 1.6;
            color: #333;
            max-width: 100%;
            margin: 0;
            padding: 0;
          }
          .header {
            text-align: center;
            margin-bottom: 30px;
            padding-bottom: 20px;
            border-bottom: 2px solid #4f46e5;
          }
          h1 {
            color: #4f46e5;
            margin: 0;
            font-size: 24px;
          }
          .summary-content h1, .summary-content h2, .summary-content h3 {
            color: #18181b;
            margin: 1.2em 0 0.4em;
            font-size: 16px;
          }
          .summary-content ul, .summary-content ol {
            padding-left: 1.4em;
          }
          .summary-content > :first-child {
            margin-top: 0;
          }
          .summary-content {
            background: #fafaf9;
            padding: 20px;
            border-radius: 8px;
            border-left: 4px solid #4f46e5;
            margin: 20px 0;
            font-size: 14px;
            line-height: 1.8;
          }
          .footer {
            margin-top: 40px;
            text-align: center;
            color: #666;
            font-size: 12px;
            border-top: 1px solid #ddd;
            padding-top: 20px;
          }
          @media print {
            body {
              -webkit-print-color-adjust: exact;
              print-color-adjust: exact;
            }
            .summary-content {
              background: #fafaf9 !important;
              border-left: 4px solid #4f46e5 !important;
            }
          }
        </style>
      </head>
      <body>
        <div class="header">
          <h1>Document Summary</h1>
        </div>
        <div class="summary-content">${contentHtml}</div>
        <div class="footer">
          Generated by LearnMate AI on ${new Date().toLocaleDateString()} at ${new Date().toLocaleTimeString()}
        </div>
      </body>
    </html>
  `;

  // Write content to the iframe
  const iframeDoc = iframe.contentDocument || iframe.contentWindow?.document;
  if (iframeDoc) {
    iframeDoc.open();
    iframeDoc.write(htmlContent);
    iframeDoc.close();

    // Wait for content to load, then trigger print dialog
    iframe.onload = () => {
      setTimeout(() => {
        if (iframe.contentWindow) {
          iframe.contentWindow.print();
          
          // Clean up the iframe after printing
          setTimeout(() => {
            document.body.removeChild(iframe);
          }, 1000);
        }
      }, 500);
    };
  }
}
