#!/usr/bin/env bash
# Regenerate backend/requirements.lock: every package (direct + transitive) pinned exactly,
# resolved for the deploy target (CPython 3.11, Linux x86_64) - the same as Render and Docker.
#
# Usage: scripts/lock-requirements.sh   (edit backend/requirements.txt first, then run this)
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
PIP="${PIP:-$ROOT/backend/venv/bin/pip}"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

"$PIP" install --dry-run --quiet --ignore-installed --only-binary=:all: \
  --python-version 3.11 --implementation cp \
  --platform manylinux_2_28_x86_64 --platform manylinux_2_17_x86_64 --platform manylinux2014_x86_64 --platform linux_x86_64 \
  --target "$WORK/target" --report "$WORK/report.json" \
  -r "$ROOT/backend/requirements.txt"

python3 - "$WORK/report.json" "$ROOT/backend/requirements.lock" <<'PY'
import json, sys
report, out = sys.argv[1], sys.argv[2]
pins = sorted((i["metadata"]["name"], i["metadata"]["version"]) for i in json.load(open(report))["install"])
with open(out, "w") as f:
    f.write("# GENERATED by scripts/lock-requirements.sh - do not edit by hand.\n")
    f.write("# Exact versions of every runtime dependency for CPython 3.11 / Linux (Render, Docker, CI).\n")
    f.write("# Source of truth for direct dependencies: requirements.txt\n")
    f.writelines(f"{name}=={version}\n" for name, version in pins)
print(f"wrote {len(pins)} pins to {out}")
PY
